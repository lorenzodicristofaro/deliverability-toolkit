def google_zones(**per_addr: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    return chain(**per_addr)


def test_propagation_consistent(world: World) -> None:  # noqa: F811
    html = prop_form(world).text
    assert 'data-verdict="consistent"' in html
    n = sum(len(e.addresses) for e in list_public_resolvers() if e.status == "verified") + 1
    assert t("tools.dns.propagation.consistent", "en", n=n) in html
    assert "192.0.2.10" in html
    assert "propagation-not-evaluated" not in html
    # one row per address, with name and operator
    assert html.count("<tr data-resolver=") == n
    assert "Google Public DNS" in html and "Cloudflare" in html
    assert t("tools.dns.propagation.differing", "en") not in html


def test_propagation_differing(world: World) -> None:  # noqa: F811
    other = [{"name": "example.com", "type": "A", "ttl": 60, "rdata": ["192.0.2.77"]}]
    use_zones(world, google_zones(**{"8.8.8.8": other}))
    r = post(world, "analyst", PROP, {"name": "example.com", "type": "A", "resolver_ids": "google"})
    html = r.text
    assert 'data-verdict="inconsistent"' in html
    assert t("tools.dns.propagation.differing", "en") in html
    assert "192.0.2.77" in html and "192.0.2.10" in html


def test_propagation_failures_are_not_evaluated_not_missing(world: World) -> None:  # noqa: F811
    fail = [{"name": "example.com", "type": "A", "state": "servfail", "rcode": 2}]
    use_zones(world, google_zones(**{a: fail for a in GOOGLE}))
    html = post(
        world,
        "analyst",
        PROP,
        {"name": "example.com", "type": "A", "resolver_ids": "google"},
    ).text
    # the failing resolvers are listed apart, with their state label, and do not make a verdict
    ne = html.split('data-testid="propagation-not-evaluated"')[1]
    assert ne.count("<li data-resolver=") == 4
    assert t("tools.dns.state.servfail", "en") in ne
    assert t("tools.dns.propagation.not_evaluated", "en") in html
    assert t("tools.dns.propagation.not_evaluated_note", "en") in html
    rows = html.split('data-testid="propagation-rows"')[1].split("</table>")[0]
    assert rows.count("<tr data-resolver=") == 1  # only the default resolver was evaluated
    assert "servfail" not in rows
    assert 'data-verdict="inconclusive"' in html
    assert t("tools.dns.propagation.differing", "en") not in html
    assert t("tools.dns.state.nxdomain", "en") not in ne
    assert t("tools.dns.state.nodata", "en") not in ne


