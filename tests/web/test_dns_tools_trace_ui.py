def use_zones(w: World, zones: dict[str, list[dict[str, Any]]]) -> None:
    backend, _ = fake_backend(zones)
    w.client.app.dependency_overrides[dns_backend] = lambda: backend  # type: ignore[attr-defined]


def chain(**overrides: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    return {**ZONES, **overrides}


def trace_form(w: World, name: str = "example.com", rtype: str = "A", **extra: str) -> Any:
    return post(w, "analyst", TRACE, {"name": name, "type": rtype}, **extra)


def prop_form(w: World, name: str = "example.com", rtype: str = "A", **extra: Any) -> Any:
    return post(w, "analyst", PROP, {"name": name, "type": rtype}, **extra)


