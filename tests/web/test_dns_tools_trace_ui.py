def test_trace_follows_referrals_and_shows_answer(world: World) -> None:  # noqa: F811
    r = trace_form(world)
    assert r.status_code == 200
    html = r.text
    assert 'data-outcome="ok"' in html
    hops = re.findall(r'<li class="dns-hop" data-kind="(\w+)" data-state="(\w+)"', html)
    assert [k for k, _ in hops] == ["referral", "referral", "answer"]
    assert all(s == "ok" for _, s in hops)
    assert "192.0.2.10" in html and "a.gtld.example.net" in html
    assert "192.0.2.3" in html  # server address of the last hop
    assert t("tools.dns.trace.referral", "en") in html
    assert t("tools.dns.trace.outcome.ok", "en") in html
    assert t("tools.dns.trace.final_answer", "en") in html
    # a referral is a referral: never an absence message
    assert t("tools.dns.state.nodata", "en") not in html
    assert t("tools.dns.state.nxdomain", "en") not in html


