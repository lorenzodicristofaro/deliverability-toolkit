@pytest.mark.parametrize(
    ("leaf", "outcome", "key", "kind"),
    [
        (LOOP, "loop", "tools.dns.trace.outcome.loop", "failure"),
        (REFUSED, "lame_delegation", "tools.dns.trace.outcome.lame", "failure"),
        (SERVFAIL, "all_failed", "tools.dns.trace.outcome.all_failed", "failure"),
        (NXD, "nxdomain", "tools.dns.trace.outcome.nxdomain", "absent"),
        (NXD_NONAUTH, "lame_delegation", "tools.dns.trace.outcome.lame", "failure"),
    ],
    ids=["loop", "refused", "servfail", "nxdomain", "nonauth-nxdomain"],
)
def test_trace_outcomes_have_own_messages(
    world: World,  # noqa: F811
    leaf: dict[str, Any],
    outcome: str,
    key: str,
    kind: str,
) -> None:
    use_zones(world, chain(**{"192.0.2.3": [leaf]}))
    html = trace_form(world).text
    assert f'data-outcome="{outcome}"' in html
    assert t(key, "en") in html
    label = re.escape(t(key, "en"))
    m = re.search(
        rf'<p class="dns-state dns-state-(\w+)" data-state="\w+" data-kind="(\w+)"[^>]*>\s*{label}',
        html,
    )
    assert m and m.group(2) == kind, html[-1500:]
    if kind == "failure":
        assert (
            "is-ok" not in html
            and 'data-state="nxdomain"' not in html.split("Result of the trace")[1][:600]
        )


