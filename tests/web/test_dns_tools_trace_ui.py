@pytest.mark.parametrize("method", ["GET", "POST"])
@pytest.mark.parametrize("path", [TRACE, PROP])
def test_role_matrix(world: World, who: str, method: str, path: str) -> None:  # noqa: F811
    r = get(world, who, path) if method == "GET" else post(world, who, path, FORMS[path])
    if who == "anon":
        assert r.status_code == (303 if method == "GET" else 401)
        if method == "GET":
            assert r.headers["location"].startswith("/login?next=")
    else:
        assert r.status_code == EXPECTED[who], r.text[:200]
    if who == "viewer":
        assert 'data-testid="forbidden"' in r.text
        assert "trace-form" not in r.text and "propagation-form" not in r.text


