def _used_keys() -> set[str]:
    found: set[str] = set()
    sources = [ROOT / "app/web/custom_checks.py"]
    sources += sorted((ROOT / "app/web/templates/custom_checks").glob("*.html"))
    sources.append(ROOT / "app/web/templates/checks/_result.html")
    for path in sources:
        found |= set(re.findall(r"""["'](web\.custom_checks\.[a-z_.]+)["']""", path.read_text()))
    return found


def test_every_custom_check_key_exists_in_both_locales() -> None:
    keys = {k for k in _used_keys() if not k.endswith(".")}
    assert len(keys) > 40
    en = json.loads((LOCALES_DIR / "en.json").read_text(encoding="utf-8"))
    it = json.loads((LOCALES_DIR / "it.json").read_text(encoding="utf-8"))
    for catalogue in (en, it):
        assert {k for k in keys if k not in catalogue} == set()
    mine = {k for k in en if k.startswith("web.custom_checks.")}
    assert mine == {k for k in it if k.startswith("web.custom_checks.")}
    assert mine <= keys  # no unused key


