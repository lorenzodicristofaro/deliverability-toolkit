@pytest.mark.parametrize(("fields", "definition"), KIND_CASES)
def test_create_edit_toggle_delete_round_trip(
    world: World, fields: dict[str, str], definition: dict[str, Any]
) -> None:
    row_id = create(world, **fields)
    row = stored(world)[0]
    assert dict(row.definition) == definition
    assert (row.kind, row.severity, row.enabled) == (fields["kind"], "medium", True)
    assert row.remediation_text == {"en": "Publish the record.", "it": "Pubblica il record."}
    listing = get(world, "owner", "/custom-checks?notice=created").text
    assert "Verification record" in listing
    assert 'data-testid="custom-flash"' in listing

    edit = send(
        world,
        "owner",
        f"/custom-checks/{row_id}/edit?scope=tenant",
        form(**{**fields, "name": "Renamed", "severity": "high", "check_key": "ignored"}),
    )
    assert edit.status_code == 303
    row = stored(world)[0]
    assert (row.name, row.severity, row.check_key) == ("Renamed", "high", "acme.verify")

    off = send(world, "owner", f"/custom-checks/{row_id}/toggle", {"enabled": "0"})
    assert off.status_code == 303
    assert stored(world)[0].enabled is False
    on = send(world, "owner", f"/custom-checks/{row_id}/toggle", {"enabled": "1"})
    assert on.status_code == 303
    assert stored(world)[0].enabled is True

    gone = send(world, "owner", f"/custom-checks/{row_id}/delete")
    assert gone.status_code == 303
    assert gone.headers["location"] == "/custom-checks?scope=tenant&notice=deleted"
    assert count(world) == 0


