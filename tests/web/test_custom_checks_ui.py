def send(
    w: World,
    who: str,
    path: str,
    data: dict[str, Any] | None = None,
    *,
    tenant_id: int | None = None,
    csrf: bool = True,
    headers: dict[str, str] | None = None,
) -> Any:
    token = _login(w, who, tenant_id)
    body = dict(data or {})
    if csrf and token:
        body = {"csrf_token": token, **body}
    return w.client.post(
        path,
        content=urlencode(body, doseq=True).encode(),
        headers={**HTML, "Content-Type": "application/x-www-form-urlencoded", **(headers or {})},
        follow_redirects=False,
    )


def send_raw(w: World, who: str, path: str, raw: bytes) -> Any:
    token = _login(w, who)
    body = urlencode({"csrf_token": token}).encode() + b"&" + raw
    return w.client.post(
        path,
        content=body,
        headers={**HTML, "Content-Type": "application/x-www-form-urlencoded"},
        follow_redirects=False,
    )


def stored(w: World) -> list[CustomCheck]:
    w.db.expire_all()
    w.db.rollback()
    rows = list(w.db.scalars(select(CustomCheck).order_by(CustomCheck.id)))
    w.db.rollback()
    return rows


def count(w: World) -> int:
    w.db.expire_all()
    w.db.rollback()
    n = int(w.db.scalar(select(func.count()).select_from(CustomCheck)) or 0)
    w.db.rollback()
    return n


def create(w: World, who: str = "owner", scope: str = "tenant", **over: Any) -> int:
    r = send(w, who, f"/custom-checks?scope={scope}", form(**over))
    assert r.status_code == 303, r.text
    rows = stored(w)
    return rows[-1].id


