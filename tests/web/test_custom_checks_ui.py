class Zone:
    """The resolver of the app under test: a recorded zone, swapped per test."""

    def __init__(self) -> None:
        self.zones: dict[str, list[dict[str, Any]]] = {"default": [txt(D, "v=spf1 -all")]}
        self.fail: dict[tuple[str, str], str] | None = None
        self.everywhere: str | None = None
        self.made: list[Scripted] = []

    def resolver(self) -> Scripted:
        r = Scripted(self.zones, self.fail, self.everywhere)
        self.made.append(r)
        return r

    @property
    def queries(self) -> list[Any]:
        return [q for r in self.made for q in r.queries]


