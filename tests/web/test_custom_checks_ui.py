def render_result(result: CheckResult, lang: str = "en") -> str:
    return env.get_template("checks/_result.html").render(
        lang=lang, t=lambda key, **params: t(key, lang, **params), result=result
    )


def custom_result(**finding_kwargs: Any) -> CheckResult:
    found = finding(
        "CUSTOM_CHECK_FAILED",
        "medium",
        {"check_key": "k", "name": "n.example", "rrtype": "TXT", "reason": "no_match"},
        ("v=spf1",),
        remediation=False,
    )
    if finding_kwargs:
        found = found.model_copy(update=finding_kwargs)
    return CheckResult.build(
        check_id="custom:tenant:k",
        target="example.org",
        findings=[found],
        evaluated=True,
        started_at=dt.datetime(2026, 1, 1, tzinfo=dt.UTC),
        duration_ms=1,
    )


def with_text(text: Any) -> CheckResult:
    found = custom_result().findings[0]
    params = {**found.params, "remediation_text": text}
    return custom_result(params=params)


