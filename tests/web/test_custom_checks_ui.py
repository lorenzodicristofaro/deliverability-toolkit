    """The writing or evaluating service methods that were called."""
    calls: list[str] = []

    def wrap(name: str) -> None:
        original = getattr(CustomChecksAdminService, name)

        def wrapper(self: Any, *args: Any, **kwargs: Any) -> Any:
            calls.append(name)
            return original(self, *args, **kwargs)

        monkeypatch.setattr(CustomChecksAdminService, name, wrapper)

    for method in ("create", "update", "delete", "prepare_test"):
        wrap(method)
    return calls


