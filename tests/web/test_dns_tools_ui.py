def lookup_form(w: World, name: str, rtype: str = "A", **extra: str) -> Any:
    return post(w, "analyst", "/tools/dns/lookup", {"name": name, "type": rtype, **extra})


def state_of(html: str, rdtype: str) -> str:
    m = re.search(rf'data-rdtype="{rdtype}".*?data-state="(\w+)"', html, re.S)
    assert m, html[:500]
    return m.group(1)


