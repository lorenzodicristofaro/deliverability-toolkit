ROUTES = (("GET", "/tools/dns"), ("POST", "/tools/dns/lookup"), ("POST", "/tools/dns/reverse"))
FORMS = {
    "/tools/dns/lookup": {"name": "example.com", "type": "A"},
    "/tools/dns/reverse": {"ip": "192.0.2.10"},
}
EXPECTED = {"anon": None, "owner": 200, "admin": 200, "analyst": 200, "viewer": 403}


@pytest.mark.parametrize("who", list(EXPECTED))
@pytest.mark.parametrize(("method", "path"), ROUTES)
def test_role_matrix(world: World, who: str, method: str, path: str) -> None:
    r = get(world, who, path) if method == "GET" else post(world, who, path, FORMS[path])
    if who == "anon":
        assert r.status_code == (303 if method == "GET" else 401)
        if method == "GET":
            assert r.headers["location"].startswith("/login?next=")
    else:
        assert r.status_code == EXPECTED[who], r.text[:200]
    if who == "viewer":
        assert 'data-testid="forbidden"' in r.text
        assert "lookup-form" not in r.text


