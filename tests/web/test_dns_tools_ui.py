FAILURES = [s for s in ResultState if s.is_failure]


class StubResolver:
    """Answers every question with one fixed failure state (the zone fixtures cannot model
    `blocked`/`error`)."""

    def __init__(self, state: ResultState) -> None:
        self.state = state
        self.identity = f"stub:{state.value}"

    async def resolve(self, question: DnsQuestion) -> DnsResult:
        return DnsResult(question, self.state, detail_code=f"stub_{self.state.value}")


@pytest.mark.parametrize("state", FAILURES, ids=lambda s: s.value)
def test_failure_states_are_never_no_record(world: World, state: ResultState) -> None:
    backend, _ = fake_backend(ZONES_UI)
    stub = StubResolver(state)
    backend = dataclasses.replace(backend, lookup=LookupResolvers(stub, lambda _e: stub))
    world.client.app.dependency_overrides[dns_backend] = lambda: backend  # type: ignore[attr-defined]
    r = lookup_form(world, "anything.example.com", "A")
    assert r.status_code == 200
    assert state_of(r.text, "A") == state.value
    assert 'data-kind="failure"' in r.text
    assert t(f"tools.dns.state.{state.value}", "en") in r.text
    assert f"stub_{state.value}" in r.text  # the reason is shown
    assert t("tools.dns.state.nxdomain", "en") not in r.text
    assert t("tools.dns.state.nodata", "en") not in r.text


def test_every_state_has_distinct_labels_in_both_languages() -> None:
    for lang in ("en", "it"):
        labels = [t(f"tools.dns.state.{s.value}", lang) for s in ResultState]
        assert len(set(labels)) == len(labels)
        assert all(label for label in labels)
    for s in FAILURES:
        assert t(f"tools.dns.state.{s.value}", "en").startswith("Could not be evaluated")
        assert t(f"tools.dns.state.{s.value}", "it").startswith("Non valutabile")


