def test_hostile_values_are_escaped(world: World) -> None:
    add_rule(world, name=HOSTILE_RULE)
    r = analyze(world, "analyst", {"html": HOSTILE_HTML, "subject": HOSTILE_SUBJECT})
    assert r.status_code == 200
    assert_no_hostile_markup(r.text)
    assert "&lt;script&gt;" in r.text  # the rule name is shown, escaped
    assert "&amp;lt;" not in r.text


