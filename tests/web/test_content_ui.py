# --- result, completeness, parity with the analyzer ---------------------------------------------


def test_result_renders_sections_and_completeness(world: World, spy: list[ContentInput]) -> None:
    add_rule(world)
    r = analyze(world, "analyst", {"html": "<p>zebraword here</p>", "subject": "Hello"})
    assert r.status_code == 200
    for section in ("sections", "rules", "findings"):
        assert f'data-testid="content-{section}"' in r.text
    assert 'data-testid="content-status"' in r.text
    assert 'data-testid="content-complete"' in r.text
    assert spy[0].html == "<p>zebraword here</p>"
    assert spy[0].subject == "Hello"
    assert spy[0].text is None
    assert spy[0].eml is None


def test_ui_matches_analyzer_result(world: World, spy: list[ContentInput]) -> None:
    add_rule(world)
    data = {"html": "<p>zebraword</p><a href='http://bit.ly/x'>click</a>", "subject": "FREE!!!"}
    html = analyze(world, "analyst", data).text
    expected = analyze_content(
        TenantContext(world.tenant_a, None),
        world.db,
        ContentInput(html=data["html"], subject=data["subject"]),
    )
    assert f'data-status="{expected.status}"' in html
    assert f'data-complete="{"true" if expected.complete else "false"}"' in html
    codes = re.findall(r'<li data-code="([^"]*)"', html)
    assert codes == [f.code for f in expected.findings]
    sections = dict(re.findall(r'<tr data-section="([^"]*)" data-status="([^"]*)"', html))
    for name in ("body", "links", "subject", "unsubscribe", "rules"):
        assert sections[name] == getattr(expected, name).status


def test_overall_complete_false_is_shown_even_when_status_ok(
    world: World, monkeypatch: pytest.MonkeyPatch
) -> None:
    real = analyze_content

    def incomplete(ctx: TenantContext, session: Any, content: ContentInput) -> ContentAnalysis:
        result = real(ctx, session, content)
        facts = result.rules.facts
        assert facts is not None
        rules = result.rules.model_copy(
            update={"facts": facts.model_copy(update={"complete": True})}
        )
        return result.model_copy(update={"status": "ok", "complete": False, "rules": rules})

    monkeypatch.setattr(content_web, "analyze_content", incomplete)
    html = analyze(world, "analyst").text
    assert 'data-status="ok"' in html
    marker = 'data-testid="content-complete" data-complete="false"'
    assert marker in html
    assert t("web.content.complete.no") in html
    assert t("web.content.complete.note") in html


