def add_rule(w: World, *, name: str = "r1", pattern: str = "zebraword") -> None:
    repo = repo_for(TenantContext(w.tenant_a, None), w.db).content_rules
    repo.create(
        {
            "kind": "keyword",
            "weight": 10,
            "category": "spam",
            "severity": "medium",
            "enabled": True,
            "name": name,
            "pattern": pattern,
            "title": "T",
        }
    )


def analyze(w: World, who: str, data: dict[str, str] | None = None, **kw: Any) -> Any:
    return post(w, who, PATH, {"text": "hello there"} if data is None else data, **kw)


def raw_post(w: World, content: bytes) -> Any:
    """A urlencoded body sent with the CSRF header (JS/HTMX style)."""
    token = _login(w, "analyst")
    assert token is not None
    return w.client.post(
        PATH,
        content=content,
        headers={
            "Accept": "text/html",
            "Content-Type": "application/x-www-form-urlencoded",
            CSRF_HEADER: token,
        },
        follow_redirects=False,
    )


def form_post(w: World, size: int, token: str | None = "", **headers: str) -> Any:
    """No-JS style: a urlencoded body of exactly `size` bytes with `csrf_token` first, a small
    valid text and padding. `token=""` means the analyst's real token."""
    real = _login(w, "analyst")
    assert real is not None
    head = "" if token is None else urlencode({"csrf_token": token or real}) + "&"
    head += urlencode({"text": "hello there"}) + "&pad="
    content = (head + "a" * (size - len(head))).encode()
    assert len(content) == size
    return w.client.post(
        PATH,
        content=content,
        headers={
            "Accept": "text/html",
            "Content-Type": "application/x-www-form-urlencoded",
            **headers,
        },
        follow_redirects=False,
    )


def assert_no_hostile_markup(html: str) -> None:
    for needle in ("<script>alert", "<img src=x", "<img onerror", '"><img'):
        assert needle not in html, needle


