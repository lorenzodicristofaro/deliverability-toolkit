def test_empty_and_malformed_forms(world: World, spy: list[ContentInput]) -> None:
    for r in (
        analyze(world, "analyst", {"text": "  \r\n", "subject": "only a subject"}),
        post(world, "analyst", PATH, {"other": "x"}),
        raw_post(world, b"\xff\xfe"),  # not UTF-8
        raw_post(world, b"text=a&text=b"),  # repeated field
        raw_post(world, b"&".join(b"f%d=1" % i for i in range(40))),  # too many fields
    ):
        assert r.status_code == 422
        assert t("web.content.error.empty") in r.text
    assert spy == []


