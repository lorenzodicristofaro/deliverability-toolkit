def _used_rule_keys() -> set[str]:
    sources = [
        ROOT / "app/web/rules.py",
        *sorted((ROOT / "app/web/templates/rules").glob("*.html")),
    ]
    found: set[str] = set()
    for path in sources:
        found |= set(
            re.findall(
                r"""["']((?:web\.rules|nav\.tools\.rules)\.[a-z_.]+)["']""", path.read_text()
            )
        )
    return found


def test_every_rules_key_exists_in_both_locales() -> None:
    keys = _used_rule_keys()
    keys = {k for k in keys if not k.endswith(".")}
    assert len(keys) > 40
    # every kind, flag and scope needs a label: listed here so a dropped value fails too
    keys |= {f"web.rules.kind.{k}" for k in ("regex", "keyword")}
    keys |= {f"web.rules.flag.{k}" for k in "imsxa"}
    keys |= {f"web.rules.scope.{k}" for k in ("tenant", "global")}
    for lang in ("en", "it"):
        catalogue = json.loads((LOCALES_DIR / f"{lang}.json").read_text(encoding="utf-8"))
        missing = {k for k in keys if k not in catalogue}
        assert missing == set(), lang


