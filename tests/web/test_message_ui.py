# --- limits and errors --------------------------------------------------------------------------


def test_empty_and_missing_field(world: World, spy: list[bytes]) -> None:
    for r in (
        analyze(world, "analyst", "   \r\n"),
        post(world, "analyst", PATH, {"other": "x"}),
        raw_post(world, b"\xff\xfe"),  # not UTF-8
        raw_post(world, b"raw=a&raw=b"),  # repeated field
    ):
        assert r.status_code == 422
        assert t("message.error.empty") in r.text
    assert spy == []


def test_nul_byte_is_a_localized_error(world: World, spy: list[bytes]) -> None:
    r = analyze(world, "analyst", "Subject: a\x00b\r\n\r\n")
    assert r.status_code == 422
    assert t("message.error.nul_byte") in r.text
    assert spy == []


def test_decoded_message_over_cap_is_413(world: World, spy: list[bytes]) -> None:
    body = urlencode({"raw": "S: " + "a" * MAX_RAW_BYTES}).encode()
    assert len(body) < MAX_BODY_BYTES
    r = raw_post(world, body)
    assert r.status_code == 413
    assert t("message.error.too_large") in r.text
    assert spy == []


def test_body_over_transport_cap_is_413(world: World, spy: list[bytes]) -> None:
    r = raw_post(world, b"raw=" + b"a" * MAX_BODY_BYTES)
    assert r.status_code == 413
    assert t("message.error.too_large") in r.text
    assert spy == []


def test_413_message_is_italian_when_asked(world: World) -> None:
    body = urlencode({"raw": "S: " + "a" * MAX_RAW_BYTES}).encode()
    token = _login(world, "analyst")
    assert token is not None
    r = world.client.post(
        PATH,
        content=body,
        headers={
            "Accept": "text/html",
            "Accept-Language": "it",
            "Content-Type": "application/x-www-form-urlencoded",
            CSRF_HEADER: token,
        },
    )
    assert r.status_code == 413
    assert t("message.error.too_large", "it") in r.text


def test_italian_page(world: World) -> None:
    r = get(world, "analyst", PATH, **{"Accept-Language": "it"})
    assert t("message.form.submit", "it") in r.text


