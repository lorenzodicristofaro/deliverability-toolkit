# --- domain routes: behaviour -----------------------------------------------------------------


def test_single_check_is_the_check_result_wire_json(world: World) -> None:
    r = call(world, "analyst", "POST", dpath(world, "assigned", "/spf"))
    assert r.status_code == 200
    assert r.headers["content-type"] == "application/json"
    body = r.json()
    assert set(body) == WIRE_KEYS
    assert body["check_id"] == "spf" and body["target"] == "assigned.example"
    assert body["status"] == "ok"
    # Exactly what the model serializes: round trip through CheckResult is the identity.
    assert json.loads(CheckResult.model_validate(body).model_dump_json()) == body


def test_all_returns_every_check_sorted(world: World) -> None:
    r = call(world, "viewer", "POST", dpath(world, "assigned", "/all"))
    assert r.status_code == 200
    body = r.json()
    assert [x["check_id"] for x in body] == sorted(CHECKS)
    assert all(set(x) == WIRE_KEYS and x["target"] == "assigned.example" for x in body)


def test_ids_keep_request_order(world: World) -> None:
    r = call(world, "owner", "POST", dpath(world, "assigned", ""), json={"ids": ["dmarc", "spf"]})
    assert r.status_code == 200
    assert [x["check_id"] for x in r.json()] == ["dmarc", "spf"]


def test_dns_failure_is_200_with_status_error(world: World) -> None:
    r = call(world, "owner", "POST", dpath(world, "unassigned", "/spf"))
    assert r.status_code == 200
