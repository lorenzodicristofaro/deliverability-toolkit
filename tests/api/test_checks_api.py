@pytest.fixture
def world(db_url: str, monkeypatch: pytest.MonkeyPatch) -> Iterator[World]:
    monkeypatch.setenv("DATABASE_URL", db_url)
    monkeypatch.setenv("SECRET_KEY", KEY)
    monkeypatch.setenv("ENCRYPTION_KEY", KEY)
    command.upgrade(Config(str(ROOT / "alembic.ini")), "head")
    engine = create_db_engine(db_url)
    db = create_session_factory(engine)()
    tenant_a, tenant_b, users, domains = _seed(db)
    settings = Settings(database_url=db_url, secret_key=KEY, encryption_key=KEY)  # type: ignore[call-arg]
    application = create_app(settings)
    backend, _ = fake_backend(ZONES)
    application.dependency_overrides[dns_backend] = lambda: backend
    try:
        with TestClient(application, raise_server_exceptions=True) as client:
            yield World(client, db, settings, tenant_a, tenant_b, users, domains)
    finally:
        db.close()
        app_engine = getattr(application.state, "db_engine", None)
        if app_engine is not None:
            app_engine.dispose()
        engine.dispose()


def dpath(world: World, which: str, tail: str) -> str:
    return f"/api/v1/domains/{world.domains[which]}/checks{tail}"


def set_toggles(world: World, user: str, toggles: dict[str, bool]) -> None:
    membership = world.db.scalars(
        select(Membership).where(Membership.user_id == world.users[user])
    ).one()
    membership.feature_toggles = toggles
    world.db.commit()


# --- domain routes: roles and tenancy ---------------------------------------------------------

ROUTES = ("/spf", "/all", "")
DOMAIN_EXPECTED = {"anon": 401, "owner": 200, "admin": 200, "analyst": 200, "viewer": 200}


def request(world: World, who: str, which: str, tail: str, **kw: Any) -> Any:
    body = {"ids": ["spf", "dmarc"]} if tail == "" else None
    return call(world, who, "POST", dpath(world, which, tail), json=body, **kw)


@pytest.mark.parametrize("tail", ROUTES)
@pytest.mark.parametrize("who", list(DOMAIN_EXPECTED))
def test_role_matrix_assigned_domain(world: World, who: str, tail: str) -> None:
    r = request(world, who, "assigned", tail)
    assert r.status_code == DOMAIN_EXPECTED[who], r.text[:200]
    if who == "anon":
        assert r.json() == {"detail": t("auth.required", "en")}


@pytest.mark.parametrize("tail", ROUTES)
@pytest.mark.parametrize(
    ("who", "status"), [("owner", 200), ("admin", 200), ("analyst", 200), ("viewer", 404)]
)
def test_unassigned_domain(world: World, who: str, status: int, tail: str) -> None:
    r = request(world, who, "unassigned", tail)
    assert r.status_code == status
    if status == 404:
        assert r.json() == {"detail": t("api.error.not_found", "en")}


@pytest.mark.parametrize("tail", ROUTES)
@pytest.mark.parametrize("who", ["owner", "admin", "analyst", "viewer"])
def test_tenant_a_cannot_run_on_tenant_b_domain(world: World, who: str, tail: str) -> None:
    r = request(world, who, "other", tail)
    assert r.status_code == 404
    assert r.json() == {"detail": t("api.error.not_found", "en")}
