@pytest.mark.parametrize("path,payload,field,reason", BAD)
def test_invalid_input_is_422_with_codes_only(
    world: World,
    path: str,
    payload: dict[str, Any] | bytes,
    field: str,
    reason: str,
    caplog: pytest.LogCaptureFixture,
) -> None:
    caplog.set_level(logging.DEBUG)
    if isinstance(payload, bytes):
        r = call(world, "analyst", "POST", f"{BASE}/{path}", content=payload)
    else:
        r = post(world, path, payload)
    assert r.status_code == 422, r.text[:200]
    detail = r.json()["detail"]
    assert detail["key"] == "api.error.invalid_request"
    assert detail["message"] == t("api.error.invalid_request", "en")
    assert detail["field"] == field
    if reason != "*":
        assert detail["reason"] == reason
    assert set(detail) == {"key", "message", "field", "reason"}
    # No echo of the offending input in the body or the logs.
    for marker in ("bad name", "not-an-ip", "bad..name", "10.0.0.1", "public:nope", "nope"):
        assert marker not in r.text
        assert marker not in "\n".join(rec.getMessage() for rec in caplog.records)


